package io.github.tianiste.skyprogression.core;

import com.google.gson.*;
import java.net.URI;
import java.net.http.*;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.util.*;
import java.util.regex.*;

/**
 * Regenerates the mod's item icon table (`src/main/resources/skyprogression-item-icons.json`) from the official
 * items resource: base material, durability, leather colour and head texture hash per SkyBlock item ID, for
 * gear, tools, accessories, pet items, reforge stones, gemstones and every item an upgrade buys or a collection names.
 * Essences, attribute shards and pets are not in the items resource; their head textures come from the
 * NotEnoughUpdates repository (MIT), pets with custom_data id "PET" and petInfo like the game's pet items.
 * Run with `./gradlew :core:extractIcons`.
 */
public final class IconExtractor {
    private static final Set<String> CATEGORIES = Set.of("HELMET", "CHESTPLATE", "LEGGINGS", "BOOTS", "NECKLACE", "CLOAK", "BELT",
            "GLOVES", "BRACELET", "DRILL", "PICKAXE", "GAUNTLET", "ACCESSORY", "DEPLOYABLE", "PET_ITEM", "REFORGE_STONE");
    private static final Pattern TEXTURE = Pattern.compile("textures\\.minecraft\\.net/texture/([0-9a-f]+)");
    private static final Pattern VALUE = Pattern.compile("Value:\"([A-Za-z0-9+/=]+)");
    private static final String NEU = "https://raw.githubusercontent.com/NotEnoughUpdates/NotEnoughUpdates-REPO/master/";
    private static final List<String> TIERS = List.of("COMMON", "UNCOMMON", "RARE", "EPIC", "LEGENDARY", "MYTHIC");

    public static void main(String[] args) throws Exception {
        HttpResponse<String> response = HttpClient.newHttpClient().send(HttpRequest.newBuilder(URI.create("https://api.hypixel.net/v2/resources/skyblock/items")).build(),
                HttpResponse.BodyHandlers.ofString());
        JsonObject root = JsonParser.parseString(response.body()).getAsJsonObject();
        if (response.statusCode() != 200 || !root.get("success").getAsBoolean()) throw new IllegalStateException("Items resource unavailable: " + response.statusCode());
        Set<String> catalog = new HashSet<>();
        Catalog.load().forEach(i -> catalog.add(i.id));
        catalog.addAll(GearUpgrades.priceIds(Catalog.load()));
        catalog.add("ENCHANTED_BOOK");
        catalog.addAll(Catalog.progressionRules().getAsJsonObject("collections").keySet());
        JsonObject out = new JsonObject();
        for (JsonElement e : root.getAsJsonArray("items")) {
            JsonObject item = e.getAsJsonObject();
            String id = item.get("id").getAsString(), category = item.has("category") ? item.get("category").getAsString() : "";
            if (!CATEGORIES.contains(category) && !id.endsWith("_GEM") && !catalog.contains(id)) continue;
            JsonObject icon = new JsonObject();
            icon.addProperty("m", item.get("material").getAsString());
            if (item.has("durability") && item.get("durability").getAsInt() != 0) icon.addProperty("d", item.get("durability").getAsInt());
            if (item.has("color")) icon.addProperty("c", item.get("color").getAsString());
            if (item.has("skin")) {
                JsonElement skin = item.get("skin");
                String value = skin.isJsonObject() ? skin.getAsJsonObject().get("value").getAsString() : skin.getAsString();
                Matcher m = TEXTURE.matcher(new String(Base64.getDecoder().decode(value), StandardCharsets.UTF_8));
                if (m.find()) icon.addProperty("t", m.group(1));
            }
            out.add(id, icon);
        }
        for (String id : catalog) if (!out.has(id) && id.startsWith("ESSENCE_")) neu(out, id, id, null);
        for (JsonElement e : get(NEU + "constants/attribute_shards.json").getAsJsonArray("attributes")) {
            JsonObject a = e.getAsJsonObject();
            String id = a.get("bazaarName").getAsString();
            if (catalog.contains(id) && !out.has(id)) neu(out, id, a.get("internalName").getAsString(), null);
        }
        StatBreakdown.petTiers().forEach((type, tiers) -> {
            if (tiers.isEmpty()) return;
            JsonObject info = new JsonObject();
            info.addProperty("type", type); info.addProperty("tier", tiers.getLast());
            neu(out, "PET_" + type, type + ";" + TIERS.indexOf(tiers.getLast()), info);
        });
        JsonObject file = new JsonObject();
        file.addProperty("_note", "Generated by ./gradlew :core:extractIcons from https://api.hypixel.net/v2/resources/skyblock/items (lastUpdated "
                + root.get("lastUpdated").getAsLong() + ").");
        file.addProperty("_license", "Essence, shard and pet head textures: NotEnoughUpdates-REPO, MIT License, Copyright (c) 2020 Moulberry.");
        file.add("items", out);
        Path target = Path.of("src/main/resources/skyprogression-item-icons.json");
        Files.writeString(target, new Gson().toJson(file));
        System.out.println("Wrote " + out.size() + " item icons to " + target);
    }

    /** A head from the NEU item file; pet: petInfo for a pet (custom_data id "PET"). Missing files are skipped. */
    private static void neu(JsonObject out, String key, String file, JsonObject pet) {
        try {
            Matcher value = VALUE.matcher(get(NEU + "items/" + file.replace(";", "%3B") + ".json").get("nbttag").getAsString());
            if (!value.find()) throw new IllegalStateException("no texture");
            Matcher m = TEXTURE.matcher(new String(Base64.getDecoder().decode(value.group(1)), StandardCharsets.UTF_8));
            if (!m.find()) throw new IllegalStateException("no texture URL");
            JsonObject icon = new JsonObject();
            icon.addProperty("m", "SKULL_ITEM"); icon.addProperty("d", 3); icon.addProperty("t", m.group(1));
            if (pet != null) { icon.addProperty("i", "PET"); icon.addProperty("p", pet.toString()); }
            out.add(key, icon);
        } catch (Exception e) {
            System.out.println("No NEU icon for " + key + " (" + file + "): " + e.getMessage());
        }
    }
    private static JsonObject get(String url) throws Exception {
        HttpResponse<String> response = HttpClient.newHttpClient().send(HttpRequest.newBuilder(URI.create(url)).build(), HttpResponse.BodyHandlers.ofString());
        if (response.statusCode() != 200) throw new IllegalStateException("HTTP " + response.statusCode());
        return JsonParser.parseString(response.body()).getAsJsonObject();
    }
}

package io.github.tianiste.skyprogression.core;

import com.google.gson.*;
import java.net.URI;
import java.net.http.*;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.util.*;

/**
 * Regenerates `core/src/main/resources/mining-reforges.json` from the NotEnoughUpdates repository (MIT): every
 * reforge whose stats include a mining stat, with its stats per rarity, item categories, reforge stone and
 * Blacksmith fee. Pass a commit SHA to pin the source; the default is master. Run with `./gradlew :core:extractNeu`.
 */
public final class NeuExtractor {
    private static final Map<String, String> STATS = Map.of("mining_speed", "MINING_SPEED", "mining_fortune", "MINING_FORTUNE",
            "gemstone_fortune", "GEMSTONE_FORTUNE", "ore_fortune", "ORE_FORTUNE", "block_fortune", "BLOCK_FORTUNE",
            "dwarven_metal_fortune", "DWARVEN_METAL_FORTUNE", "mining_spread", "MINING_SPREAD", "gemstone_spread", "GEMSTONE_SPREAD",
            "pristine", "PRISTINE");
    private static final Map<String, List<String>> TYPES = Map.of("PICKAXE", List.of("PICKAXE", "DRILL", "GAUNTLET"),
            "ARMOR", List.of("HELMET", "CHESTPLATE", "LEGGINGS", "BOOTS"),
            "EQUIPMENT", List.of("NECKLACE", "CLOAK", "BELT", "GLOVES", "BRACELET"));

    public static void main(String[] args) throws Exception {
        String ref = args.length > 0 ? args[0] : "master";
        JsonArray out = new JsonArray();
        for (String file : List.of("reforges", "reforgestones")) {
            JsonObject data = get("https://raw.githubusercontent.com/NotEnoughUpdates/NotEnoughUpdates-REPO/" + ref + "/constants/" + file + ".json");
            for (var e : data.entrySet()) {
                JsonObject r = e.getValue().getAsJsonObject();
                JsonElement types = r.get("itemTypes");
                List<String> categories = types.isJsonPrimitive() ? TYPES.getOrDefault(types.getAsString(), List.of(types.getAsString())) : List.of();
                JsonObject stats = new JsonObject();
                boolean mining = false;
                if (r.has("reforgeStats")) for (var tier : r.getAsJsonObject("reforgeStats").entrySet()) {
                    JsonObject kept = new JsonObject();
                    for (var s : tier.getValue().getAsJsonObject().entrySet())
                        if (STATS.containsKey(s.getKey())) kept.add(STATS.get(s.getKey()), s.getValue());
                    mining |= !kept.isEmpty();
                    stats.add(tier.getKey(), kept);
                }
                if (!mining || categories.isEmpty()) continue;
                JsonObject o = new JsonObject();
                o.addProperty("name", r.get("reforgeName").getAsString());
                if (file.equals("reforgestones")) {
                    o.addProperty("stone", r.get("internalName").getAsString());
                    o.add("costs", r.get("reforgeCosts"));
                }
                JsonArray cats = new JsonArray();
                categories.forEach(cats::add);
                o.add("categories", cats);
                o.add("stats", stats);
                if (r.has("reforgeAbility") && r.get("reforgeAbility").isJsonPrimitive())
                    o.addProperty("ability", r.get("reforgeAbility").getAsString().replaceAll("§.", "").replaceAll("[\\uE000-\\uF8FF\\u1805\\u2668\\u2744]", "").replaceAll(" +", " ").strip());
                out.add(o);
            }
        }
        JsonObject file = new JsonObject();
        file.addProperty("_note", "Generated by ./gradlew :core:extractNeu from NotEnoughUpdates-REPO constants/reforges.json and reforgestones.json (" + ref + ").");
        file.addProperty("_license", "Source data: NotEnoughUpdates-REPO, MIT License, Copyright (c) 2020 Moulberry. https://github.com/NotEnoughUpdates/NotEnoughUpdates-REPO/blob/master/LICENSE");
        file.add("reforges", out);
        Path target = Path.of("core/src/main/resources/mining-reforges.json");
        Files.writeString(target, new GsonBuilder().setPrettyPrinting().create().toJson(file) + "\n", StandardCharsets.UTF_8);
        System.out.println("Wrote " + out.size() + " mining reforges to " + target);
    }
    private static JsonObject get(String url) throws Exception {
        HttpResponse<String> response = HttpClient.newHttpClient().send(HttpRequest.newBuilder(URI.create(url)).build(), HttpResponse.BodyHandlers.ofString());
        if (response.statusCode() != 200) throw new IllegalStateException(url + " returned " + response.statusCode());
        return JsonParser.parseString(response.body()).getAsJsonObject();
    }
}
